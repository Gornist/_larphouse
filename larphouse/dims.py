"""Размеры системы, мм. X — вдоль конька, Y — поперёк, Z — вверх."""
import math

# щит и брусок
PW, H = 997, 2400            # щит (997 — зазор 4,5 мм на сторону в проёме 3000)
T, D = 25, 50                # брусок 25×50
PLY = 3                      # фанера обшивки (ФСФ 3 мм, лист 1220×2440)
PLY_G = 9                    # фанера косынок
SD = D + PLY                 # толщина пролёта
GAP = (3000 - 3 * PW) / 2    # зазор пролёта в проёме, на сторону

# каркас
POST = 100                   # стойка 100×100
OPEN = 3000                  # проём между стойками
PITCH = POST + OPEN          # 3100 — шаг сетки
LEZ = 50                     # лежень 50×100 плашмя (высота 50)
BEAM = (50, 100)             # обвязка 50×100 на ребро
BL = OPEN - 4                # лежень и обвязка между стойками, зазор 2 мм
Z0 = LEZ                     # низ пролёта = верх лежня
ZB = Z0 + H + 10             # низ обвязки (зазор 10 над пролётом)
ZP = ZB + BEAM[1]            # верх обвязки = верх стойки = низ затяжек
WC = 25                      # ось пяты фермы на обвязке от наружной грани

# болты
BH = 11                      # отверстие под болт М10
SPAN_O = D / 2 + PLY         # 28 — ось болтов пролёта от наружной грани
ANG_O = 77                   # ось болта уголка лежня
TOP_O = 75                   # ось болта уголка обвязки
BOLT_Z = (300, 1000, 1700)   # болты щит-щит в пролёте
# высоты болтов от земли разнесены по направлениям, чтобы отверстия в стойке не пересекались
Z_ANG = {'x': (80, ZB + 25), 'y': (115, ZB + 75)}                 # уголки: низ, верх
Z_SPAN = {('x', 'L'): (650, 1850), ('x', 'R'): (750, 1950),        # пролёт — стойка
          ('y', 'L'): (450, 1250), ('y', 'R'): (550, 1350)}
END_Z = tuple(sorted(z - Z0 for v in Z_SPAN.values() for z in v))  # те же болты в крайних щитах пролёта

# крыша
ALPHA = math.radians(17.6)
TAN, COS, SIN = math.tan(ALPHA), math.cos(ALPHA), math.sin(ALPHA)
